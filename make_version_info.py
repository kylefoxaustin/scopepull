#!/usr/bin/env python3
"""Write version_info.txt for PyInstaller from scopepull.__version__.

A Windows exe with no version resource -- no product name, no company, no file
version -- looks, to Defender's heuristics, like something that was thrown
together to be thrown away. This gives scopepull.exe a Properties > Details tab
like any other program. Run before `pyinstaller scopepull.spec`; the spec
references the file it writes.
"""

import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = (HERE / "src" / "scopepull" / "__init__.py").read_text(encoding="utf-8")
match = re.search(r'^__version__\s*=\s*"([^"]+)"', src, re.M)
if match is None:  # pragma: no cover
    raise SystemExit("couldn't find __version__ in src/scopepull/__init__.py")
version = match.group(1)
nums = [int(x) for x in re.findall(r"\d+", version)][:4]
nums += [0] * (4 - len(nums))
tup = tuple(nums)

text = f"""# generated by make_version_info.py from scopepull.__version__ -- do not edit
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={tup},
    prodvers={tup},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        StringStruct('CompanyName', 'Kyle Fox'),
        StringStruct('FileDescription', 'scopepull -- gets the night off your smart scope'),
        StringStruct('FileVersion', '{version}'),
        StringStruct('InternalName', 'scopepull'),
        StringStruct('LegalCopyright', 'MIT License. https://github.com/kylefoxaustin/scopepull'),
        StringStruct('OriginalFilename', 'scopepull.exe'),
        StringStruct('ProductName', 'scopepull'),
        StringStruct('ProductVersion', '{version}')
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""
out = HERE / "version_info.txt"
out.write_text(text, encoding="utf-8")
print(f"wrote {out} for scopepull {version}")
